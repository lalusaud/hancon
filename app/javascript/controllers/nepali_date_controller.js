const FIRST_YEAR = 2000
const LAST_YEAR = 2090
const ANCHOR_UTC = Date.UTC(1943, 3, 14)
const NEPAL_OFFSET_MS = (5 * 60 + 45) * 60 * 1000
const DAY_MS = 24 * 60 * 60 * 1000
const MONTHS = ["बैशाख", "जेठ", "असार", "श्रावण", "भदौ", "असोज", "कार्तिक", "मंसिर", "पौष", "माघ", "फाल्गुन", "चैत्र"]
const DIGITS = "०१२३४५६७८९"

const dayPeriod = (hour) => {
  if (hour >= 4 && hour < 12) return "बिहान"
  if (hour >= 12 && hour < 16) return "दिउँसो"
  if (hour >= 16 && hour < 19) return "साँझ"
  return "राती"
}

const toNepaliDigits = (value) => String(value).replace(/\d/g, (d) => DIGITS[d])
const pad = (value) => String(value).padStart(2, "0")

// Shows today's Bikram Sambat date and the current Nepal time, ticking every second.
export default class extends Controller {
  connect() {
    this.render()
    this.timer = setInterval(() => this.render(), 5000)
  }

  disconnect() {
    clearInterval(this.timer)
  }

  render() {
    const nepalNow = new Date(Date.now() + NEPAL_OFFSET_MS)
    const bs = this.bikramSambat(nepalNow)
    if (!bs) return

    const hours = nepalNow.getUTCHours()
    const time = [hours % 12 || 12, nepalNow.getUTCMinutes()].map(pad).join(":")

    this.element.textContent = `${MONTHS[bs.month]} ${toNepaliDigits(pad(bs.day))}, ${toNepaliDigits(bs.year)} - ${dayPeriod(hours)} ${toNepaliDigits(time)}`
  }

  bikramSambat(nepalNow) {
    let days = Math.floor((Date.UTC(nepalNow.getUTCFullYear(), nepalNow.getUTCMonth(), nepalNow.getUTCDate()) - ANCHOR_UTC) / DAY_MS)

    for (let year = FIRST_YEAR; year <= LAST_YEAR; year++) {
      for (let month = 0; month < 12; month++) {
        const length = MONTH_DAYS[year][month]
        if (days < length) return { year, month, day: days + 1 }
        days -= length
      }
    }
    return null
  }
}
